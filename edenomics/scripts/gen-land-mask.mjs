/**
 * Generates a compact land bitmask used by the 3D globe.
 *
 * The globe draws a Fibonacci-sphere point cloud. Rather than shipping
 * coordinates for every land dot, we ship one bit per point (base64) and
 * regenerate the same deterministic point positions at runtime.
 *
 * Run with:  npm i -D world-atlas topojson-client && node scripts/gen-land-mask.mjs
 * Output:    lib/data/land-mask.ts
 */
import { readFileSync, writeFileSync } from "node:fs";
import { feature } from "topojson-client";

const POINT_COUNT = 9000;

const topology = JSON.parse(
  readFileSync(new URL("../node_modules/world-atlas/land-110m.json", import.meta.url), "utf8"),
);
const land = feature(topology, topology.objects.land);

/** Flatten to a list of rings, each with a bounding box for cheap rejection. */
const rings = [];
for (const f of land.features) {
  const polygons =
    f.geometry.type === "Polygon" ? [f.geometry.coordinates] : f.geometry.coordinates;
  for (const polygon of polygons) {
    for (const ring of polygon) {
      let minX = Infinity;
      let minY = Infinity;
      let maxX = -Infinity;
      let maxY = -Infinity;
      for (const [x, y] of ring) {
        if (x < minX) minX = x;
        if (x > maxX) maxX = x;
        if (y < minY) minY = y;
        if (y > maxY) maxY = y;
      }
      // Outer rings come first in GeoJSON winding; treat every ring as a
      // toggle so holes (lakes) correctly punch through.
      rings.push({ ring, minX, minY, maxX, maxY });
    }
  }
}

function inRing(ring, x, y) {
  let inside = false;
  for (let i = 0, j = ring.length - 1; i < ring.length; j = i++) {
    const [xi, yi] = ring[i];
    const [xj, yj] = ring[j];
    if (yi > y !== yj > y && x < ((xj - xi) * (y - yi)) / (yj - yi) + xi) inside = !inside;
  }
  return inside;
}

function isLand(lon, lat) {
  let inside = false;
  for (const r of rings) {
    if (lon < r.minX || lon > r.maxX || lat < r.minY || lat > r.maxY) continue;
    if (inRing(r.ring, lon, lat)) inside = !inside;
  }
  return inside;
}

const GOLDEN_ANGLE = Math.PI * (3 - Math.sqrt(5));
const bytes = new Uint8Array(Math.ceil(POINT_COUNT / 8));
let landCount = 0;

for (let i = 0; i < POINT_COUNT; i++) {
  const y = 1 - (i / (POINT_COUNT - 1)) * 2; // 1 -> -1
  const theta = GOLDEN_ANGLE * i;
  const lat = Math.asin(y) * (180 / Math.PI);
  let lon = ((theta * (180 / Math.PI)) % 360) - 180;
  if (lon < -180) lon += 360;
  if (isLand(lon, lat)) {
    bytes[i >> 3] |= 1 << (i & 7);
    landCount++;
  }
}

const base64 = Buffer.from(bytes).toString("base64");

writeFileSync(
  new URL("../lib/data/land-mask.ts", import.meta.url),
  `// Generated by scripts/gen-land-mask.mjs — do not edit by hand.
// One bit per Fibonacci-sphere point (${POINT_COUNT} points, ${landCount} over land),
// derived from Natural Earth 110m land polygons via the world-atlas package.

export const LAND_POINT_COUNT = ${POINT_COUNT};

export const LAND_MASK_BASE64 =
  "${base64}";
`,
  "utf8",
);

console.log(`wrote lib/data/land-mask.ts — ${landCount}/${POINT_COUNT} points on land`);
